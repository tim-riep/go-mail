//go:build ignore

// nfc_tables_gen.go generates nfc_tables.go from the Unicode Character
// Database. It is run by hand:
//
//	go run nfc_tables_gen.go UnicodeData.txt DerivedNormalizationProps.txt
//
// The input files are the Unicode Character Database files of the version
// named in the header of DerivedNormalizationProps.txt. They must belong to
// the same Unicode version as the Go toolchain's unicode.Version; the test
// TestUnicodeVersion checks this.
//
// Primary source: https://www.unicode.org/Public/<version>/ucd/
// Mirror used for 15.0.0 (ICU release-73-2, identical files):
// https://github.com/unicode-org/icu/tree/release-73-2/icu4c/source/data/unidata
//
// The generated tables carry the SHA-256 of both inputs so the generation
// can be verified against the official files.
package main

import (
	"bufio"
	"crypto/sha256"
	"fmt"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

type rng struct {
	lo, hi rune
	v      uint8
}

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: go run nfc_tables_gen.go UnicodeData.txt DerivedNormalizationProps.txt")
		os.Exit(2)
	}
	udata, err := os.ReadFile(os.Args[1])
	check(err)
	dprops, err := os.ReadFile(os.Args[2])
	check(err)

	version := regexp.MustCompile(`DerivedNormalizationProps-([0-9.]+)\.txt`).FindSubmatch(dprops)
	if version == nil {
		check(fmt.Errorf("cannot find version in %s", os.Args[2]))
	}

	// Pass 1: canonical combining classes and canonical decompositions.
	ccc := map[rune]uint8{}
	decomp := map[rune][2]rune{} // direct canonical decomposition; [1] is 0 for singletons
	sc := bufio.NewScanner(strings.NewReader(string(udata)))
	for sc.Scan() {
		f := strings.Split(sc.Text(), ";")
		if len(f) < 6 {
			continue
		}
		cp, err := strconv.ParseUint(f[0], 16, 32)
		check(err)
		c, err := strconv.ParseUint(f[3], 10, 8)
		check(err)
		if c != 0 {
			ccc[rune(cp)] = uint8(c)
		}
		d := f[5]
		if d == "" || strings.HasPrefix(d, "<") {
			continue // no decomposition or a compatibility one
		}
		parts := strings.Fields(d)
		if len(parts) < 1 || len(parts) > 2 {
			check(fmt.Errorf("unexpected canonical decomposition %q for %04X", d, cp))
		}
		a, err := strconv.ParseUint(parts[0], 16, 32)
		check(err)
		var b uint64
		if len(parts) == 2 {
			b, err = strconv.ParseUint(parts[1], 16, 32)
			check(err)
		}
		decomp[rune(cp)] = [2]rune{rune(a), rune(b)}
	}
	check(sc.Err())

	// Pass 2: NFC_QC and Full_Composition_Exclusion.
	qc := map[rune]uint8{}
	excl := map[rune]bool{}
	sc = bufio.NewScanner(strings.NewReader(string(dprops)))
	for sc.Scan() {
		line := sc.Text()
		if i := strings.IndexByte(line, '#'); i >= 0 {
			line = line[:i]
		}
		f := strings.Split(line, ";")
		for i := range f {
			f[i] = strings.TrimSpace(f[i])
		}
		if len(f) < 2 {
			continue
		}
		lo, hi := parseRange(f[0])
		switch {
		case f[1] == "Full_Composition_Exclusion":
			for r := lo; r <= hi; r++ {
				excl[r] = true
			}
		case f[1] == "NFC_QC" && len(f) >= 3:
			var v uint8
			switch f[2] {
			case "N":
				v = 1
			case "M":
				v = 2
			default:
				check(fmt.Errorf("unexpected NFC_QC value %q", f[2]))
			}
			for r := lo; r <= hi; r++ {
				qc[r] = v
			}
		}
	}
	check(sc.Err())

	// Primary composites: canonical pairs whose composite is not excluded.
	type pair struct{ a, b, c rune }
	var pairs []pair
	for c, ab := range decomp {
		if excl[c] || ab[1] == 0 {
			continue
		}
		pairs = append(pairs, pair{ab[0], ab[1], c})
	}
	sort.Slice(pairs, func(i, j int) bool {
		if pairs[i].a != pairs[j].a {
			return pairs[i].a < pairs[j].a
		}
		return pairs[i].b < pairs[j].b
	})
	for i := 1; i < len(pairs); i++ {
		if pairs[i].a == pairs[i-1].a && pairs[i].b == pairs[i-1].b {
			check(fmt.Errorf("duplicate primary composite pair %U %U", pairs[i].a, pairs[i].b))
		}
	}

	// Consistency check: every second element of a pair must be NFC_QC=M.
	for _, p := range pairs {
		if qc[p.b] != 2 {
			check(fmt.Errorf("pair second element %U is not NFC_QC=Maybe", p.b))
		}
	}

	var out strings.Builder
	fmt.Fprintf(&out, "// Code generated by nfc_tables_gen.go; DO NOT EDIT.\n\n")
	fmt.Fprintf(&out, "// Source: Unicode Character Database %s\n", version[1])
	fmt.Fprintf(&out, "//   UnicodeData.txt                SHA-256 %x\n", sha256.Sum256(udata))
	fmt.Fprintf(&out, "//   DerivedNormalizationProps.txt  SHA-256 %x\n\n", sha256.Sum256(dprops))
	fmt.Fprintf(&out, "package rec\n\n")
	fmt.Fprintf(&out, "// nfcUnicodeVersion is the Unicode version of the tables below.\n")
	fmt.Fprintf(&out, "const nfcUnicodeVersion = %q\n\n", version[1])

	fmt.Fprintf(&out, "// cccRanges lists every code point with a non-zero canonical combining\n// class as inclusive ranges, sorted by code point.\n")
	fmt.Fprintf(&out, "var cccRanges = []runeRange{\n")
	for _, r := range toRanges(ccc) {
		fmt.Fprintf(&out, "\t{0x%04X, 0x%04X, %d},\n", r.lo, r.hi, r.v)
	}
	fmt.Fprintf(&out, "}\n\n")

	fmt.Fprintf(&out, "// nfcQCRanges lists every code point whose NFC_Quick_Check property is\n// No (1) or Maybe (2) as inclusive ranges, sorted by code point.\n")
	fmt.Fprintf(&out, "var nfcQCRanges = []runeRange{\n")
	for _, r := range toRanges(qc) {
		fmt.Fprintf(&out, "\t{0x%04X, 0x%04X, %d},\n", r.lo, r.hi, r.v)
	}
	fmt.Fprintf(&out, "}\n\n")

	fmt.Fprintf(&out, "// decompTable lists the direct canonical decomposition of every code point\n// that has one, sorted by code point. Singletons have b == 0. Hangul\n// syllables are handled algorithmically.\n")
	fmt.Fprintf(&out, "var decompTable = []decompEntry{\n")
	cps := make([]rune, 0, len(decomp))
	for cp := range decomp {
		cps = append(cps, cp)
	}
	sort.Slice(cps, func(i, j int) bool { return cps[i] < cps[j] })
	for _, cp := range cps {
		fmt.Fprintf(&out, "\t{0x%04X, 0x%04X, 0x%04X},\n", cp, decomp[cp][0], decomp[cp][1])
	}
	fmt.Fprintf(&out, "}\n\n")

	fmt.Fprintf(&out, "// compPairs lists every primary composite as (first, second, composite),\n// sorted by (first, second). Hangul syllables are handled algorithmically.\n")
	fmt.Fprintf(&out, "var compPairs = []compEntry{\n")
	for _, p := range pairs {
		fmt.Fprintf(&out, "\t{0x%04X, 0x%04X, 0x%04X},\n", p.a, p.b, p.c)
	}
	fmt.Fprintf(&out, "}\n")

	check(os.WriteFile("nfc_tables.go", []byte(out.String()), 0o644))
	fmt.Printf("Unicode %s: %d ccc ranges, %d quick-check ranges, %d decompositions, %d composition pairs\n",
		version[1], len(toRanges(ccc)), len(toRanges(qc)), len(decomp), len(pairs))
}

func parseRange(s string) (rune, rune) {
	if lo, hi, ok := strings.Cut(s, ".."); ok {
		a, err := strconv.ParseUint(lo, 16, 32)
		check(err)
		b, err := strconv.ParseUint(hi, 16, 32)
		check(err)
		return rune(a), rune(b)
	}
	a, err := strconv.ParseUint(s, 16, 32)
	check(err)
	return rune(a), rune(a)
}

func toRanges(m map[rune]uint8) []rng {
	keys := make([]rune, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Slice(keys, func(i, j int) bool { return keys[i] < keys[j] })
	var out []rng
	for _, k := range keys {
		v := m[k]
		if n := len(out); n > 0 && out[n-1].hi+1 == k && out[n-1].v == v {
			out[n-1].hi = k
			continue
		}
		out = append(out, rng{k, k, v})
	}
	return out
}

func check(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
